<?php
/**
 * Exports the product page configuration of the PHP app (libraries/product_pdp_profiles.php) as a Laravel
 * config file: profiles (labels, field order, metrics), use-case defaults per profile and variant, spec
 * aliases, list-slug to profile map and package component names. Data only, so Laravel never copies it by hand.
 *
 *   docker cp tools/migration/export_pdp_config.php pts-php81-local:/tmp/export.php
 *   docker exec pts-php81-local php /tmp/export.php > backend/config/pdp.php
 */
if (PHP_SAPI !== 'cli') exit(1);
$lib = '/var/www/html/libraries/product_pdp_profiles.php';
require $lib;
$source = file_get_contents($lib);

preg_match('/function productPdpSpecAliases.*?\$aliases = array\((.*?)\n\s*\);/s', $source, $aliasBody);
preg_match_all("/'([a-z0-9_]+)' => array\(/", $aliasBody[1] ?? '', $aliasKeys);
$aliases = array();
foreach ($aliasKeys[1] as $key) $aliases[$key] = productPdpSpecAliases($key);

preg_match('/function productPdpUseCaseDefaults.*?\$variants = array\((.*?)\n\s{8}\);/s', $source, $variantBody);
preg_match_all("/\n\s{12}'([a-z0-9_]+)' => array\(/", $variantBody[1] ?? '', $variantKeys);
$useCases = array('profiles' => array(), 'variants' => array());
foreach (productPdpProfileKeys() as $key) $useCases['profiles'][$key] = productPdpUseCaseDefaults($key);
foreach ($variantKeys[1] as $variant) $useCases['variants'][$variant] = productPdpUseCaseDefaults('lighting', $variant);

preg_match('/function productPdpProfileFromSlug.*?\$map = array\((.*?)\);/s', $source, $slugBody);
preg_match_all("/'([a-z0-9-]+)' => '([a-z_]+)'/", $slugBody[1] ?? '', $slugPairs, PREG_SET_ORDER);
$slugMap = array();
foreach ($slugPairs as $pair) $slugMap[$pair[1]] = $pair[2];

preg_match('/function productNormalizePackageContents.*?\$canonical = array\((.*?)\);/s', $source, $packageBody);
preg_match_all("/'([^']+)' => '([^']+)'/u", $packageBody[1] ?? '', $packagePairs, PREG_SET_ORDER);
$package = array();
foreach ($packagePairs as $pair) $package[$pair[1]] = $pair[2];

$config = array(
    'profiles' => productPdpProfiles(),
    'use_cases' => $useCases,
    'spec_aliases' => $aliases,
    'list_slug_profiles' => $slugMap,
    'package_components' => $package,
);
echo "<?php\n\n// Generated by tools/migration/export_pdp_config.php from libraries/product_pdp_profiles.php on ".date('Y-m-d').".\n// Product page profiles: labels, field order, metrics and use-case defaults. Candidate for an Admin editor.\nreturn ".var_export($config, true).";\n";
